"""
Builds the royal-intro scene layers from the approved Reference A artwork.

    python tools/intro/build_intro_assets.py [--preview]

Source:  docs/reference/reference-a-royal-intro.jpg (864 x 1536, supplied by the family)
Output:  public/intro/*.webp  (each layer at 1x = 864-wide stage, and 2x = 1.5 x scale)
         src/components/intro/sceneManifest.json  (layer rectangles in stage pixels)

The reference is one flat painting. To animate it like a real scene, this script:
  1. removes the painted lettering and the painted "Tap to open" button (the
     live page renders those as real, accessible, crisp HTML instead);
  2. cuts the painting into depth layers — backdrop, two palace doors, garland
     frames, the envelope (pocket, flap, seal halves, pedestal), brass lamp
     stands and the foreground lamps / lotus bowls;
  3. paints in what each moving layer used to hide (the garden beyond the doors,
     the steps behind the envelope, the envelope's inside) so nothing tears when
     the doors swing and the camera moves.
Nothing here is downloaded or generated by a model: every pixel is either the
family's reference painting or a deterministic fill derived from it.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import cv2
import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'docs' / 'reference' / 'reference-a-royal-intro.jpg'
OUT = ROOT / 'public' / 'intro'
MANIFEST = ROOT / 'src' / 'components' / 'intro' / 'sceneManifest.json'
PREVIEW = ROOT / 'tools' / 'out'
W, H = 864, 1536
HI_SCALE = 1.5

rng = np.random.default_rng(20261115)


# ---------------------------------------------------------------- helpers
def load() -> np.ndarray:
    img = cv2.imread(str(SRC), cv2.IMREAD_COLOR)
    assert img is not None and img.shape[:2] == (H, W), f'unexpected reference image {SRC}'
    return img


def poly_mask(points, feather: float = 0.0, shape=(H, W)) -> np.ndarray:
    """Float mask (0..1) of a polygon, optionally feathered with a Gaussian."""
    m = np.zeros(shape, np.float32)
    cv2.fillPoly(m, [np.array(points, np.int32)], 1.0, lineType=cv2.LINE_AA)
    if feather > 0:
        m = cv2.GaussianBlur(m, (0, 0), feather)
    return np.clip(m, 0, 1)


def ellipse_mask(cx, cy, rx, ry, feather=0.0, shape=(H, W)) -> np.ndarray:
    m = np.zeros(shape, np.float32)
    cv2.ellipse(m, (int(cx), int(cy)), (int(rx), int(ry)), 0, 0, 360, 1.0, -1, lineType=cv2.LINE_AA)
    if feather > 0:
        m = cv2.GaussianBlur(m, (0, 0), feather)
    return np.clip(m, 0, 1)


def stroke_mask(img, box, k=25, thr=40, dilate=2) -> np.ndarray:
    """Thin painted strokes (lettering, filigree) inside a box: pixels that differ from a median-smoothed copy."""
    x0, y0, x1, y1 = box
    reg = img[y0:y1, x0:x1]
    med = cv2.medianBlur(reg, k)
    diff = cv2.absdiff(reg, med).astype(np.int32).sum(axis=2)
    m = (diff > thr).astype(np.uint8) * 255
    m = cv2.dilate(m, np.ones((3, 3), np.uint8), iterations=dilate)
    full = np.zeros((H, W), np.uint8)
    full[y0:y1, x0:x1] = m
    return full


def smooth_curve(points, n=24):
    """Catmull-Rom through the given points -> dense polyline."""
    pts = np.array(points, np.float32)
    out = []
    for i in range(len(pts) - 1):
        p0 = pts[max(i - 1, 0)]
        p1, p2 = pts[i], pts[i + 1]
        p3 = pts[min(i + 2, len(pts) - 1)]
        for t in np.linspace(0, 1, n, endpoint=False):
            t2, t3 = t * t, t * t * t
            out.append(0.5 * ((2 * p1) + (-p0 + p2) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t2 + (-p0 + 3 * p1 - 3 * p2 + p3) * t3))
    out.append(pts[-1])
    return [tuple(map(float, p)) for p in out]


def grabcut_mask(img, sure_fg, probable_fg, box, feather=0.8) -> np.ndarray:
    """GrabCut seeded with hand-placed polygons (sure / probable foreground) inside a box."""
    cv2.setRNGSeed(1115)
    mask = np.full((H, W), cv2.GC_BGD, np.uint8)
    x0, y0, x1, y1 = box
    mask[y0:y1, x0:x1] = cv2.GC_PR_BGD
    for p in probable_fg:
        cv2.fillPoly(mask, [np.array(p, np.int32)], cv2.GC_PR_FGD)
    for p in sure_fg:
        cv2.fillPoly(mask, [np.array(p, np.int32)], cv2.GC_FGD)
    bgd, fgd = np.zeros((1, 65), np.float64), np.zeros((1, 65), np.float64)
    cv2.grabCut(np.clip(img, 0, 255).astype(np.uint8), mask, None, bgd, fgd, 6, cv2.GC_INIT_WITH_MASK)
    m = np.where((mask == cv2.GC_FGD) | (mask == cv2.GC_PR_FGD), 1.0, 0.0).astype(np.float32)
    # keep the largest connected pieces only (drop specks)
    n, lab, stats, _ = cv2.connectedComponentsWithStats((m > 0).astype(np.uint8))
    keep = np.zeros_like(m)
    for i in range(1, n):
        if stats[i, cv2.CC_STAT_AREA] > 400:
            keep[lab == i] = 1
    return np.clip(cv2.GaussianBlur(keep, (0, 0), feather), 0, 1)


def fill_region(img, region, down=4, grain=2.4) -> np.ndarray:
    """Paint over a large region with a smooth continuation of its surroundings (low-res inpaint + grain)."""
    small = cv2.resize(np.clip(img, 0, 255).astype(np.uint8), (W // down, H // down), interpolation=cv2.INTER_AREA)
    sm = cv2.resize((region > 0.02).astype(np.uint8) * 255, (W // down, H // down), interpolation=cv2.INTER_NEAREST)
    sm = cv2.dilate(sm, np.ones((3, 3), np.uint8))
    filled = cv2.inpaint(small, sm, 6, cv2.INPAINT_NS)
    big = cv2.resize(filled, (W, H), interpolation=cv2.INTER_CUBIC).astype(np.float32)
    big += rng.normal(0, grain, (H, W, 1))
    a = cv2.GaussianBlur(region.astype(np.float32), (0, 0), 2.0)[..., None]
    return img * (1 - a) + big * a


def step_rows_fill(img, region, strips, y0, y1, sigma_y=1.2, override=None) -> np.ndarray:
    """Fill a region with horizontal bands (marble steps / floor) sampled per row from narrow strips beside it."""
    out = img.copy()
    src = np.clip(img, 0, 255).astype(np.float32)
    prev = None
    rows = {}
    for y in range(y0, y1):
        samples = np.concatenate([src[y, a:b] for a, b in strips], 0)
        b, g, r = samples[:, 0], samples[:, 1], samples[:, 2]
        lum = 0.11 * b + 0.59 * g + 0.3 * r
        ok = (r - g < 55) & (lum > 60) & (lum < 245)  # no pink petals / lotus, no flames, no deep shadow
        rows[y] = np.median(samples[ok], 0) if ok.sum() >= 6 else prev
        if override is not None and y in override:
            rows[y] = override[y]
        prev = rows[y] if rows[y] is not None else prev
    # rows still empty at the top take the first valid row
    first = next(v for v in rows.values() if v is not None)
    prof = np.array([rows[y] if rows[y] is not None else first for y in range(y0, y1)], np.float32)
    prof = cv2.GaussianBlur(prof[:, None, :], (0, 0), sigmaX=0.1, sigmaY=sigma_y)[:, 0, :]
    band = np.repeat(prof[:, None, :], W, axis=1)
    # gentle horizontal light falloff + fine marble grain
    xs = (np.arange(W) - W / 2) / (W / 2)
    band *= (1.0 - 0.06 * xs**2)[None, :, None]
    band += rng.normal(0, 2.2, band.shape).astype(np.float32)
    a = cv2.GaussianBlur(region[y0:y1].astype(np.float32), (0, 0), 1.5)[..., None]
    out[y0:y1] = out[y0:y1] * (1 - a) + band * a
    return out


def mirror_down_fill(img, hole, cols) -> np.ndarray:
    """For each column, replace hole pixels by mirroring the intact pixels just above the hole (carved door panels)."""
    out = img.copy()
    for x in range(*cols):
        ys = np.where(hole[:, x] > 0)[0]
        if len(ys) == 0:
            continue
        top = ys.min()
        for y in ys:
            sy = max(2 * top - y - 1, 0)
            out[y, x] = img[sy, x]
    a = cv2.GaussianBlur((hole > 0).astype(np.float32), (0, 0), 1.0)[..., None]
    soft = cv2.GaussianBlur(np.clip(out, 0, 255).astype(np.uint8), (0, 0), 0.8).astype(np.float32)
    return out * (1 - a * 0.5) + soft * (a * 0.5)


def unsharp(img: Image.Image, radius=1.1, percent=55, threshold=2) -> Image.Image:
    return img.filter(ImageFilter.UnsharpMask(radius=radius, percent=percent, threshold=threshold))


# layers registry: name -> (bgr, alpha, bbox)
LAYERS: dict[str, dict] = {}


def add_layer(name, bgr, alpha, pad=2, bbox=None, quality=84):
    a = np.clip(alpha, 0, 1)
    if bbox is None:
        ys, xs = np.where(a > 0.004)
        x0, x1 = max(int(xs.min()) - pad, 0), min(int(xs.max()) + pad + 1, W)
        y0, y1 = max(int(ys.min()) - pad, 0), min(int(ys.max()) + pad + 1, H)
    else:
        x0, y0, x1, y1 = bbox
    LAYERS[name] = {'bgr': bgr, 'alpha': a, 'box': (x0, y0, x1, y1), 'quality': quality}


def export():
    OUT.mkdir(parents=True, exist_ok=True)
    manifest = {'stage': {'w': W, 'h': H, 'hiScale': HI_SCALE}, 'layers': {}}
    total = 0
    for name, L in LAYERS.items():
        x0, y0, x1, y1 = L['box']
        rgb = cv2.cvtColor(np.clip(L['bgr'][y0:y1, x0:x1], 0, 255).astype(np.uint8), cv2.COLOR_BGR2RGB)
        a = (L['alpha'][y0:y1, x0:x1] * 255).round().astype(np.uint8)
        opaque = bool(a.min() == 255)
        base = Image.fromarray(rgb)
        if not opaque:
            base = Image.merge('RGBA', (*base.split(), Image.fromarray(a)))
        for suffix, scale in (('', 1.0), ('@2x', HI_SCALE)):
            im = base
            if scale != 1.0:
                im = base.resize((round(base.width * scale), round(base.height * scale)), Image.LANCZOS)
                if opaque:
                    im = unsharp(im)
                else:
                    r, g, b, al = im.split()
                    rgbim = unsharp(Image.merge('RGB', (r, g, b)))
                    im = Image.merge('RGBA', (*rgbim.split(), al))
            path = OUT / f'{name}{suffix}.webp'
            im.save(path, 'WEBP', quality=L['quality'], method=6, alpha_quality=88)
            total += path.stat().st_size
        manifest['layers'][name] = {'x': x0, 'y': y0, 'w': x1 - x0, 'h': y1 - y0}
    MANIFEST.write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    print(f'{len(LAYERS)} layers, {total / 1024:.0f} KB total (1x + 2x)')


# ---------------------------------------------------------------- build
def main(preview: bool):
    src = load()
    img = src.copy()

    # 1. remove painted lettering + filigree (the page renders these as real HTML)
    text = np.zeros((H, W), np.uint8)
    text |= stroke_mask(src, (296, 132, 572, 226), k=25, thr=38)  # top ornament + "A ROYAL INVITATION"
    orn = stroke_mask(src, (318, 226, 546, 270), k=25, thr=38)  # lower ornament
    orn[228:, 516:] = 0  # protect the palm fronds to the right of the ornament
    orn[236:, :336] = 0  # …and to the left
    text |= orn
    text |= stroke_mask(src, (196, 1156, 664, 1298), k=31, thr=46)  # names, divider, date
    img = cv2.inpaint(img, text, 7, cv2.INPAINT_TELEA)

    # the painted "TAP TO OPEN" button and its ornaments (covered by the live button)
    btn = np.zeros((H, W), np.uint8)
    cv2.rectangle(btn, (254, 1318), (610, 1422), 255, -1)
    cv2.rectangle(btn, (228, 1350), (640, 1392), 255, -1)
    cv2.circle(btn, (430, 1333), 33, 255, -1)
    cv2.rectangle(btn, (400, 1400), (462, 1450), 255, -1)
    btn = cv2.GaussianBlur(btn, (0, 0), 1.5)
    btn = (btn > 20).astype(np.uint8) * 255
    img = step_rows_fill(img.astype(np.float32), cv2.GaussianBlur(btn.astype(np.float32) / 255, (0, 0), 3), [(200, 226), (640, 666)], 1290, 1456, sigma_y=3)
    # re-grain the smooth inpainted area so it matches the painted floor
    grain = rng.normal(0, 3.2, (H, W, 1)).astype(np.float32)
    bm = cv2.GaussianBlur(btn.astype(np.float32) / 255, (0, 0), 6)[..., None]
    img = np.clip(img.astype(np.float32) + grain * bm, 0, 255)

    clean = img.copy()  # text-free painting, every pixel as painted

    # 2. backdrop: fill what the doors and the envelope hide
    backdrop = clean.copy()

    # 2a. beyond the doors: the garden continues to either side of the doorway.
    #     Mirror the garden outward from each jamb, softened with depth haze.
    door_h = 880
    garden = clean[:door_h].copy()
    for jamb, direction, x_from, x_to in ((276, -1, 96, 276), (588, 1, 588, 766)):
        for x in range(x_from, x_to):
            d = abs(x - jamb)
            sx = jamb - direction * (d + 6)  # mirror across the jamb, skipping the jamb itself
            sx = int(np.clip(sx, 280, 584))
            backdrop[:door_h, x] = garden[:, sx]
        span = slice(x_from, x_to)
        region = backdrop[:door_h, span].astype(np.uint8)
        blurred = cv2.GaussianBlur(region, (0, 0), 3.2).astype(np.float32)
        # warm haze + a little darkness toward the outer wall
        dist = np.abs(np.arange(x_from, x_to) - jamb).astype(np.float32) / (x_to - x_from)
        haze = np.array([170, 205, 245], np.float32)  # BGR warm light
        k = (0.18 + 0.25 * dist)[None, :, None]
        shade = (1 - 0.35 * dist)[None, :, None]
        backdrop[:door_h, span] = (blurred * (1 - k) + haze * k) * shade

    # 2b. behind the envelope + pedestal and behind the foreground lamps: a smooth
    #     continuation of the steps / marble floor around them
    env_fill = poly_mask([(176, 746), (688, 746), (746, 1146), (112, 1146)], 1.0)
    walkway = np.median(np.clip(clean[736:742, 300:560], 0, 255).reshape(-1, 3), 0)
    steps_top = {y: walkway * (1.0 - 0.10 * (y - 740) / 130) for y in range(740, 872)}
    backdrop = step_rows_fill(backdrop, env_fill, [(150, 176), (690, 716)], 740, 1150, sigma_y=2.0, override=steps_top)
    add_layer('backdrop', backdrop, np.ones((H, W), np.float32), bbox=(0, 0, W, H), quality=82)

    # 3. palace doors (hinged at their outer edges; free edges by the doorway)
    door_l = poly_mask([(98, 0), (277, 0), (277, 872), (98, 872)], 0.6)
    door_r = poly_mask([(587, 0), (764, 0), (764, 876), (587, 876)], 0.6)
    doors_src = clean.copy()
    # jasmine strands hanging in front of the door tops belong to the frame, not the doors
    strands = np.zeros((H, W), np.uint8)
    cv2.rectangle(strands, (118, 0), (170, 158), 255, -1)
    cv2.rectangle(strands, (696, 0), (750, 210), 255, -1)
    doors_src = cv2.inpaint(np.clip(doors_src, 0, 255).astype(np.uint8), strands, 9, cv2.INPAINT_TELEA).astype(np.float32)
    # lamp stands (separate layer in front) and the envelope cover the door bottoms: paint the door on
    props_l = grabcut_mask(clean,
                           [[(20, 790), (110, 790), (110, 820), (20, 820)], [(45, 840), (75, 840), (75, 1060), (45, 1060)],
                            [(90, 975), (160, 975), (160, 1030), (90, 1030)]],
                           [[(0, 748), (140, 748), (142, 840), (100, 850), (100, 950), (195, 950), (195, 1060), (150, 1110), (0, 1110)]],
                           (0, 730, 200, 1120))
    props_r = grabcut_mask(clean,
                           [[(745, 790), (850, 790), (850, 820), (745, 820)], [(790, 840), (815, 840), (815, 1060), (790, 1060)],
                            [(705, 965), (770, 965), (770, 1020), (705, 1020)]],
                           [[(864, 735), (722, 735), (722, 840), (760, 850), (760, 940), (682, 940), (682, 1050), (720, 1110), (864, 1110)]],
                           (670, 720, 864, 1120))
    in_front = np.maximum(np.maximum(props_l, props_r), poly_mask([(180, 748), (684, 748), (746, 1146), (112, 1146)]))
    hole = ((in_front > 0.05) & (np.maximum(door_l, door_r) > 0)).astype(np.uint8) * 255
    doors_src = mirror_down_fill(doors_src, cv2.dilate(hole, np.ones((5, 5), np.uint8)), (90, 772))
    add_layer('door-left', doors_src, door_l)
    add_layer('door-right', doors_src, door_r)

    # 4. garland frames: jasmine columns + pillars at the sides, strands over the door tops
    bright = (cv2.cvtColor(np.clip(clean, 0, 255).astype(np.uint8), cv2.COLOR_BGR2GRAY) > 150).astype(np.float32)
    bright = cv2.GaussianBlur(cv2.dilate(bright, np.ones((5, 5), np.uint8)), (0, 0), 1.2)
    strand_l = np.zeros((H, W), np.float32)
    strand_l[0:160, 116:172] = 1
    strand_r = np.zeros((H, W), np.float32)
    strand_r[0:212, 694:752] = 1
    frame_l = np.maximum(poly_mask([(0, 0), (100, 0), (100, 742), (0, 742)], 0.8), strand_l * bright)
    frame_r = np.maximum(poly_mask([(763, 0), (W, 0), (W, 742), (763, 742)], 0.8), strand_r * bright)
    add_layer('frame-left', clean, frame_l)
    add_layer('frame-right', clean, frame_r)

    # 5. envelope: pocket (front), flap, seal halves, inside, pedestal
    tl, tr = (207.0, 752.0), (656.0, 752.0)
    bl, br = (182.0, 1033.0), (681.0, 1033.0)
    left_pipe = smooth_curve([tl, (213, 765), (265, 807), (315, 845), (360, 872), (384, 890), (430, 906)])
    right_pipe = smooth_curve([(430, 906), (476, 890), (497, 877), (540, 850), (590, 815), (650, 765), tr])
    flap_poly = [tl] + left_pipe + right_pipe + [tr]
    body = poly_mask([tl, tr, br, bl], 0.6)
    flap = poly_mask(flap_poly, 0.6)
    pocket = np.clip(body - flap, 0, 1)
    pedestal = poly_mask([(150, 1028), (712, 1028), (742, 1058), (742, 1142), (116, 1142), (116, 1058)], 1.0)
    pocket_layer = np.maximum(pocket, pedestal)

    # the wax seal: a horizontal crack splits it — the top half lifts with the flap,
    # the bottom half (and the tassel) stays on the pocket
    seal_c, seal_r = (430, 897), 50
    seal = ellipse_mask(*seal_c, seal_r, seal_r, 0.7)
    crack_y = np.full(W, 899.0)
    for x in range(W):
        crack_y[x] = 899 + 3.0 * np.sin(x * 0.55) + 2.0 * np.sin(x * 1.7 + 1.3)
    yy = np.arange(H)[:, None]
    top_side = (yy < crack_y[None, :]).astype(np.float32)
    seal_top = seal * top_side
    seal_bottom = seal * (1 - top_side)

    # seal pixels must not stay painted on the flap / pocket underneath
    flap_only = np.clip(flap - seal, 0, 1)
    pocket_with_seal_bottom = np.clip(np.maximum(pocket_layer - seal, 0) + seal_bottom, 0, 1)

    add_layer('envelope-pocket', clean, pocket_with_seal_bottom)
    add_layer('envelope-flap', clean, flap_only)
    add_layer('seal-top', clean, seal_top)

    # the inside of the envelope (back panel seen through the open V) and the flap lining
    inside = np.zeros((H, W, 3), np.float32)
    velvet = np.array([38, 52, 14], np.float32)  # BGR deep emerald velvet in shadow
    yy2 = (np.arange(H)[:, None] - 752) / 160.0
    inside[:] = velvet
    inside *= (0.55 + 0.45 * np.clip(yy2, 0, 1))[..., None]  # darker toward the deep inside
    inside += rng.normal(0, 4.0, (H, W, 1))
    inside = cv2.GaussianBlur(inside, (0, 0), 0.6)
    add_layer('envelope-inside', inside, flap, quality=80)

    lining = np.zeros((H, W, 3), np.float32)
    lining[:] = np.array([52, 74, 22], np.float32)
    shade = np.clip(1.15 - (np.arange(H)[:, None] - 752) / 220.0, 0.6, 1.15)
    lining *= shade[..., None]
    lining += rng.normal(0, 5.0, (H, W, 1))
    lining = cv2.GaussianBlur(lining, (0, 0), 0.7)
    # gold piping along the lining edge
    edge = np.zeros((H, W), np.float32)
    cv2.polylines(edge, [np.array(left_pipe + right_pipe, np.int32)], False, 1.0, 3, lineType=cv2.LINE_AA)
    gold = np.array([70, 160, 214], np.float32)
    lining = lining * (1 - edge[..., None]) + gold * edge[..., None]
    add_layer('envelope-lining', lining, flap, quality=80)

    # 6. brass lamp stands and lotus beside the pedestal (in front of the doors)
    add_layer('props-left', clean, props_l)
    add_layer('props-right', clean, props_r)

    # 7. foreground lamps, lotus bowls and candles — soft edges run through the plain floor
    fg_l = poly_mask([(0, 1100), (120, 1100), (175, 1215), (205, 1330), (330, 1395), (360, 1536), (0, 1536)], 7)
    fg_r = poly_mask([(W, 1095), (720, 1095), (690, 1205), (640, 1270), (600, 1400), (560, 1536), (W, 1536)], 7)
    add_layer('foreground-left', clean, fg_l)
    add_layer('foreground-right', clean, fg_r)

    # the camera pushes in past the foreground lamps, so the floor behind them is painted in too
    fg_hole = np.clip(np.maximum(fg_l, fg_r) * 1.4 - 0.25, 0, 1)
    backdrop = step_rows_fill(backdrop, fg_hole, [(232, 258), (606, 632), (420, 444)], 1090, H, sigma_y=7)
    LAYERS['backdrop']['bgr'] = backdrop

    export()

    if preview:
        PREVIEW.mkdir(parents=True, exist_ok=True)
        cv2.imwrite(str(PREVIEW / 'clean.png'), np.clip(clean, 0, 255).astype(np.uint8))
        cv2.imwrite(str(PREVIEW / 'backdrop.png'), np.clip(backdrop, 0, 255).astype(np.uint8))
        # recomposite all layers in stacking order: should equal the clean painting
        comp = backdrop.copy()
        for name in ['door-left', 'door-right', 'frame-left', 'frame-right', 'envelope-pocket', 'envelope-flap', 'seal-top',
                     'props-left', 'props-right', 'foreground-left', 'foreground-right']:
            L = LAYERS[name]
            a = L['alpha'][..., None]
            comp = comp * (1 - a) + L['bgr'] * a
        cv2.imwrite(str(PREVIEW / 'recomposite.png'), np.clip(comp, 0, 255).astype(np.uint8))
        diff = np.abs(comp - clean).mean()
        print(f'recomposite mean abs diff vs clean painting: {diff:.2f}')


